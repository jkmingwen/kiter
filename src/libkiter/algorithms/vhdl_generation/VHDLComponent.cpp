void VHDLComponent::addHSInputSignal(const std::string& signalName) {
  if (std::find(hsInputSignals.begin(),
                hsInputSignals.end(),
                signalName) == hsInputSignals.end()) {
    hsInputSignals.push_back(signalName);
  }
}

void VHDLComponent::addHSOutputSignal(const std::string& signalName) {
  if (std::find(hsOutputSignals.begin(),
                hsOutputSignals.end(),
                signalName) == hsOutputSignals.end()) {
    hsOutputSignals.push_back(signalName);
  }
}

void VHDLComponent::addInputSignal(models::Dataflow *const dataflow,
                                   const Edge e) {
  std::string signalName = dataflow->getEdgeName(e);
  // only add signal if it's not already in the vector
  if (std::find(inputSignals.begin(),
                inputSignals.end(),
                signalName) == inputSignals.end()) {
    inputSignals.push_back(signalName);
  }
}

void VHDLComponent::addOutputSignal(models::Dataflow *const dataflow,
                                    const Edge e) {
  std::string signalName = dataflow->getEdgeName(e);
  // only add signal if it's not already in the vector
  if (std::find(outputSignals.begin(),
                outputSignals.end(),
                signalName) == outputSignals.end()) {
    outputSignals.push_back(signalName);
  }
}

void VHDLComponent::setStartTimes(std::vector<TIME_UNIT> times,
                                  std::vector<TIME_UNIT> popTime,
                                  TIME_UNIT slack) {
  if (!times.size()) {
    VERBOSE_WARNING("Adding empty vector of start times for "
                    << this->getUniqueName());
  }
  // execution time port mapping definition
  for (int n = 0; auto time : times) {
    if (componentType == "input_selector") {
      if (implementationType == TT) {
        VERBOSE_ASSERT(times.size() == inputPorts.size(),
                       "Number of start times and input ports don't match");
        addGenericMapping("exec_time_" + std::to_string(n),
                          std::to_string((int)(time + slack)), "integer");
      }
    } else if (componentType == "output_selector") {
      if (implementationType == TT) {
        VERBOSE_ASSERT(times.size() == outputPorts.size(),
                       "Number of start times (" << times.size() << ") and output ports (" << outputPorts.size()<< ") don't match");
        addGenericMapping("exec_time_" + std::to_string(n),
                          std::to_string((int)(time + slack)), "integer");
      }
    } else if (componentType == "delay") {
      if (popTime.size() > 1) {
        VERBOSE_WARNING("More than 1 pop time defined for buffer; using first "
                        "time in vector");
      }
      if (popTime.front() == 0 && slack == 0) {
        VERBOSE_ERROR("Buffer with pop time = 0 (" << this->getUniqueName() << "), requires slack of >= 1 using -pSLACK=slack");
      }
      addGenericMapping("push_start", std::to_string((int)(time + slack)),
                        "integer");
      // Subtract 1 from pop time to account for 1 cycle delay between
      // pop time and data output
      addGenericMapping("pop_start", std::to_string((int)(popTime.front() - 1 + slack)), "integer");
    } else if (componentType == "sbuffer") {
      if (popTime.size() > 1) {
        VERBOSE_WARNING("More than 1 pop time defined for buffer; using first "
                        "time in vector");
      }
      if (popTime.front() == 0 && slack == 0) {
        VERBOSE_ERROR("Buffer with pop time = 0 (" << this->getUniqueName() << "), requires slack of >= 1 using -pSLACK=slack");
      }
      addGenericMapping("push_start", std::to_string((int)(time + slack)),
                        "integer");
      // Subtract 1 from pop time to account for 1 cycle delay between
      // pop time and data output
      addGenericMapping("pop_start", std::to_string((int)(popTime.front() - 1 + slack)), "integer");
    } else if (componentType == "shiftreg") {
      addGenericMapping("load", std::to_string((int)(time + slack + 1)), "integer");
      pipoNumbers["load"] = (int)(time + slack + 1);
    }
    n++;
  }
}

void VHDLComponent::addPortMapping(std::string port, std::string signal,
                                   std::string type, std::string direction,
                                   int dataWidth) {
  // slv type needs to have a defined width
  if (type == "std_logic_vector") {
    type += "(" + std::to_string(dataWidth - 1) + " downto 0)";
  }
  portMappings[port] = signal;
  ports[port] = direction + " " + type;
}

void VHDLComponent::addHSPortMapping(std::string portPrefix, std::string signal,
                                     int id, std::string direction) {
  portPrefix = portPrefix + "_" + direction;
  std::string rdyPort = portPrefix + "_ready_" + std::to_string(id);
  std::string vldPort = portPrefix + "_valid_" + std::to_string(id);
  std::string dataPort = portPrefix + "_data_" + std::to_string(id);
  std::string rdySignal = signal + "_READY";
  std::string vldSignal = signal + "_VALID";
  std::string dataSignal = signal + "_DATA";

  if (direction == "in") {
    addPortMapping(rdyPort, rdySignal, "std_logic", "out");
    addPortMapping(vldPort, vldSignal, "std_logic", "in");
    addPortMapping(dataPort, dataSignal, "std_logic_vector", "in");
  } else { // out
    addPortMapping(rdyPort, rdySignal, "std_logic", "in");
    addPortMapping(vldPort, vldSignal, "std_logic", "out");
    addPortMapping(dataPort, dataSignal, "std_logic_vector", "out");
  }
}

void VHDLComponent::addGenericMapping(std::string port, std::string signal,
                                      std::string type, int dataWidth,
                                      std::string defaultVal) {
  // slv type needs to have a defined width
  if (type == "std_logic_vector") {
    type += "(" + std::to_string(dataWidth - 1) + " downto 0)";
  }
  if (!defaultVal.empty()) {
    type += " := " + defaultVal;
  }
  genericMappings[port] = signal;
  genericPorts[port] = type;
}

void VHDLComponent::addExternalPort(std::string port, std::string signal,
                                    std::string type, std::string direction,
                                    int dataWidth, std::string defaultVal) {
  if (direction == "in") {
    topInputPorts.push_back(port);
  } else {
    topOutputPorts.push_back(port);
  }
  if (!defaultVal.empty()) {
    type += " := " + defaultVal;
  }
  topSignalTypes[port] = type;
  topSignalWidths[port] = dataWidth;
}

