/**
   Generate VHDL port declarations according to a given port map where:
   [key: port name, value: signal/type].

   @param portMap Populated using addPortMapping().

   @param terminate Whether the port declarations should have a terminating
   delimiter (default = true).

   @param replacements Optional map of signal names that should be replaced
   (key), and their corresponding replacements (value).

   @param relation Defines the syntax for how the port relates to the signal
   (default = ":").

   @param delim Defines the delimiter between each port declaration
   (default = ";").

   @param term Defines the terminating character after the last port is declared
   (default = "").

   @return A string of port declarations.
 */
std::string
VHDLComponent::genPortList(std::map<std::string, std::string> portMap,
                           bool terminate,
                           std::map<std::string, std::string> replacements,
                           std::string relation,
                           std::string delim,
                           std::string term) const {
  std::stringstream codeOut;
  int padAmt = 4;
  std::string t(padAmt, ' ');
  std::string lineEnder = delim;
  std::string r = " " + relation + " "; // spaces for legibility
  for (auto &[port, sigType] : portMap) {
    std::string signal = sigType;
    if (replacements.count(sigType)) {
      signal = replacements[signal];
    }
    if (port == portMap.rbegin()->first && terminate) {
      lineEnder = term;
    }
    codeOut << t << port << r << signal << lineEnder << std::endl;
  }
  return codeOut.str();
}


// Generate the VHDL declaration code for the component
// - dataWidth (default: 34): bit width of data on the input/output ports
std::string VHDLComponent::genDeclaration() const {
  std::stringstream codeOut;
  std::string t = "    "; // indentation: 4 spaces
  codeOut << "component " << implRefName << " is"
          << std::endl;
    if (genericPorts.size()) {
      codeOut << "generic (" << std::endl;
      codeOut << genPortList(genericPorts);
      codeOut << ");" << std::endl;
    }
    if (ports.size()) {
      codeOut << "port (" << std::endl;
      codeOut << genPortList(ports);
      codeOut << ");" << std::endl;
    }
  codeOut << "end component;" << std::endl;

  return codeOut.str();
}

std::string VHDLComponent::genEntityDecl() const {
  std::stringstream codeOut;
  codeOut << "entity " << implRefName << " is"
          << std::endl;
  if (genericPorts.size()) {
    codeOut << "generic (" << std::endl;
    codeOut << genPortList(genericPorts);
    codeOut << ");" << std::endl;
  }
  if (ports.size()) {
    codeOut << "port (" << std::endl;
    codeOut << genPortList(ports);
    codeOut << ");" << std::endl;
  }
  codeOut << "end " << implRefName << ";" << std::endl;

  return codeOut.str();
}

std::string VHDLComponent::genPortMapping(int id, std::map<std::string, std::string> replacements) const {
  std::stringstream codeOut;
  codeOut << portMapName << "_" << id << " : " << implRefName << std::endl;
  if (genericMappings.size()) {
    codeOut << "generic map (" << std::endl;
    codeOut << genPortList(genericMappings, true, replacements, "=>", ",");
    codeOut << ")" << std::endl;
  }
  if (portMappings.size()) {
    codeOut << "port map (" << std::endl;
    codeOut << genPortList(portMappings, true, replacements, "=>", ",");
    codeOut << ");" << std::endl;
  }

  return codeOut.str();
}

// Generate VHDL implementation of the given component --- determined by component type
void VHDLComponent::genImplementation(std::string refDir,
                                      std::string dstDir) const {
  const auto copyOptions = std::filesystem::copy_options::update_existing |
        std::filesystem::copy_options::recursive;
  std::string refFileName = implRefName + ".vhdl";
  std::string dstFileName = portMapName + ".vhdl";
  if (implementationType == TT) {
    if (componentType == "input_selector") {
      refFileName = "s_input_selector.vhdl";
    } else if (componentType == "output_selector") { // output selector
      refFileName = "s_output_selector.vhdl";
    } else if (componentType == "broadcast") {
      refFileName = "broadcast.vhdl";
    } else if (componentType == "const_value") {
      refFileName = "const_value_n_outputs.vhdl";
    } else if (componentType == "sbuffer") {
      // refFileName = "sbuffer.vhdl"; // already set by default
      // extra implementation files for sbuffer
      std::filesystem::copy(refDir + refFileName,
                            dstDir + refFileName, copyOptions);
      std::filesystem::copy(refDir + "sbuffer_n.vhdl",
                            dstDir + "sbuffer_n.vhdl", copyOptions);
      std::filesystem::copy(refDir + "sbuffer_bypass.vhdl",
                            dstDir + "sbuffer_bypass.vhdl", copyOptions);
      std::filesystem::copy(refDir + "sbuffer_one.vhdl",
                            dstDir + "sbuffer_one.vhdl", copyOptions);
    } else if (componentType == "shiftreg") {
      refFileName = "pipo_shift_reg.vhdl";
      // extra implementation files for shift register
      std::filesystem::copy(refDir + "pipo_shift_reg_n.vhdl",
                            dstDir + "pipo_shift_reg_n.vhdl", copyOptions);
      std::filesystem::copy(refDir + "pipo_shift_reg_one.vhdl",
                            dstDir + "pipo_shift_reg_one.vhdl", copyOptions);
      std::filesystem::copy(refDir + "pipo_shift_reg_zero.vhdl",
                            dstDir + "pipo_shift_reg_zero.vhdl", copyOptions);
    } else if (std::count(uiTypes.begin(), uiTypes.end(), componentType)) {
      refDir += "/operators/";
    } else if (componentType == "delay") {
      std::filesystem::copy(refDir + "delay_tt.vhdl",
                            dstDir + "delay.vhdl", copyOptions);
    } else {
      refDir += "/operators/";
      dstFileName = portMapName + "_flopoco_f" + std::to_string(opFreq) + ".vhdl";
    }
  } else if (implementationType == GS) {
    if (componentType == "input_selector") {
      refFileName = "t_input_selector.vhdl";
    } else if (componentType == "output_selector") { // output selector
      refFileName = "t_output_selector.vhdl";
    } else if (componentType == "broadcast") {
      refFileName = "broadcast.vhdl";
    } else if (componentType == "const_value") {
      refFileName = "const_value_n_outputs.vhdl";
    } else if (componentType == "sbuffer") {
      // refFileName = "sbuffer.vhdl"; // already set by default
      // extra implementation files for sbuffer
      std::filesystem::copy(refDir + "sbuffer_t.vhdl",
                            dstDir + "sbuffer_t.vhdl", copyOptions);
      std::filesystem::copy(refDir + "sbuffer_t_n.vhdl",
                            dstDir + "sbuffer_t_n.vhdl", copyOptions);
      std::filesystem::copy(refDir + "sbuffer_t_bypass.vhdl",
                            dstDir + "sbuffer_t_bypass.vhdl", copyOptions);
      std::filesystem::copy(refDir + "sbuffer_t_one.vhdl",
                            dstDir + "sbuffer_t_one.vhdl", copyOptions);
    } else if (componentType == "shiftreg") {
      refFileName = "pipo_shift_reg.vhdl";
      // extra implementation files for shift register
      std::filesystem::copy(refDir + "pipo_shift_reg_n.vhdl",
                            dstDir + "pipo_shift_reg_n.vhdl", copyOptions);
      std::filesystem::copy(refDir + "pipo_shift_reg_one.vhdl",
                            dstDir + "pipo_shift_reg_one.vhdl", copyOptions);
      std::filesystem::copy(refDir + "pipo_shift_reg_zero.vhdl",
                            dstDir + "pipo_shift_reg_zero.vhdl", copyOptions);
    } else if (componentType == "delay") {
      std::filesystem::copy(refDir + "delay_gs.vhdl",
                            dstDir + "delay.vhdl", copyOptions);
    } else {
      refDir += "/operators/";
      dstFileName = portMapName + "_flopoco_f" + std::to_string(opFreq) + ".vhdl";
    }
  } else { // data driven implementation
    if (componentType == "broadcast") {
      refFileName = "hs_splitter.vhdl";
      dstFileName = implRefName + ".vhdl";
    } else if (componentType == "input_selector") {
      refFileName = "input_selector.vhdl";
    } else if (componentType == "output_selector") {
      refFileName = "output_selector.vhdl";
    } else if (componentType == "const_value") {
      refFileName = "const_value_n_outputs.vhdl";
    } else if (std::count(uiTypes.begin(), uiTypes.end(), componentType)) {
      refFileName = "ui_template.vhdl";
    } else if (componentType == "hs_fifo") {
      refFileName = "hs_fifo.vhdl";
      std::filesystem::copy(refDir + "hs_fifo.vhdl",
                            dstDir + "hs_fifo.vhdl", copyOptions);
      std::filesystem::copy(refDir + "hs_fifo_n.vhdl",
                            dstDir + "hs_fifo_n.vhdl", copyOptions);
      std::filesystem::copy(refDir + "hs_fifo_zero.vhdl",
                            dstDir + "hs_fifo_zero.vhdl", copyOptions);
      std::filesystem::copy(refDir + "hs_fifo_one.vhdl",
                            dstDir + "hs_fifo_one.vhdl", copyOptions);
    } else if (componentType == "delay") {
      refFileName = "delay.vhdl";
    } else { // FPC operator and HS wrapper
      refFileName =
          "flopoco_hs_interface_" + std::to_string(inputPorts.size()) + ".vhdl";
      // copy over FPC operator implementation
      std::filesystem::copy(refDir + "/operators/" + implementationName + "_f" +
                                std::to_string(opFreq) + ".vhdl",
                            dstDir + implementationName + "_f" +
                            std::to_string(opFreq) + ".vhdl", copyOptions);
    }
  }
  copyFileAndReplaceWords(refDir + refFileName, dstDir + dstFileName,
                          implReplacementMap);
}

